import test from "node:test";
import assert from "node:assert/strict";
import { createHash } from "node:crypto";
import { spawnSync } from "node:child_process";
import { mkdtemp, readFile, rm } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import {
  createCinematicBrandSvg,
  createCinematicOverlaySvg,
  encodeCinematicSpan,
  parseBeatId,
  planCinematicTimeline,
} from "./p3_cinematic_timeline.mjs";

function command(name, args) {
  const result = spawnSync(name, args, {
    encoding: "utf8", timeout: 120000,
    env: { PATH: process.env.PATH ?? "/usr/bin:/bin" },
  });
  assert.equal(result.status, 0, name + ": " + (result.stderr ?? "").slice(-1000));
  return result.stdout;
}
const visuals = Array.from({length: 19}, (_, i) =>
  ({kind: "text-card", title: "Beat " + i, body: "Scientific explanation " + i}));
visuals[14] = {kind: "chart", title: "Measured ozone values", bars: [
  {label: "Year one", value: 92}, {label: "Year two", value: 105},
]};
visuals[15] = {kind: "text-card", title: "Recovery & projections",
  body: "The actual observation differs from the projected long-term recovery."};
visuals[16] = {kind: "text-card", title: "What scientists monitor",
  body: "Conditions in the stratosphere and ozone concentration."};

test("one source video spans three independent overlays and drops original audio", async () => {
  const root = await mkdtemp(join(tmpdir(), "p3-cinematic-"));
  try {
    const file = join(root, "offline-synthetic.mp4");
    command("ffmpeg", [
      "-hide_banner", "-loglevel", "error", "-nostdin", "-y",
      "-f", "lavfi", "-i", "testsrc2=size=640x360:rate=24",
      "-f", "lavfi", "-i", "sine=frequency=523:sample_rate=48000",
      "-t", "8", "-c:v", "libx264", "-threads:v", "1",
      "-pix_fmt", "yuv420p", "-c:a", "aac", file,
    ]);
    const asset = {
      id: "ci-synthetic-clip", motifId: "one-continuous-shot",
      kind: "video", path: file, sceneId: "beat-15", endSceneId: "beat-17",
      sha256: createHash("sha256").update(await readFile(file)).digest("hex"),
      sourceUrl: "https://example.org/ci-generated", creator: "CI synthetic source",
      credit: "Offline synthetic test footage", captureDate: "2026-11-13",
      licenseUrl: "https://example.org/ci-only",
      licenseEvidence: "Generated by test command; never approved for publication",
      rightsReviewedBy: "automated-fixture-only", rightsReviewedAt: "2026-11-13",
      rightsApproved: true, editorialApproved: true, thirdPartyRightsCleared: true,
    };
    const manifest = {schemaVersion: 1, assets: [asset]};
    const beatFrames = Array(19).fill(48);
    const photoBeats = Array(19).fill(null);
    photoBeats[0] = 1;
    const inputs = {manifest, assetRoot: root, beatFrames,
      beatVisualAssets: photoBeats, beatVisuals: visuals};
    const plan = await planCinematicTimeline(inputs);
    assert.equal(plan.starts.size, 1);
    assert.deepEqual([...plan.occupied].sort(), [14, 15, 16]);
    assert.equal(plan.timelineFrames, 19 * 48);
    const span = plan.starts.get(14);
    assert.equal(span.durationFrames, 144);
    assert.equal(span.visuals.length, 3);
    assert.equal(parseBeatId("beat-19"), 18);
    assert.throws(() => parseBeatId("beat-20"), /beat-01/);

    const overlay = createCinematicOverlaySvg({
      kind: "text-card", title: "<Earth & sky>",
      body: "Real data & careful interpretation",
    }, 15);
    assert.match(overlay, /&lt;Earth &amp; sky&gt;/);
    assert.match(overlay, /fill-opacity="0.74"/);
    assert.doesNotMatch(overlay, /<Earth & sky>/);
    assert.match(createCinematicBrandSvg(asset.credit, asset.captureDate),
      /NOT FOR PUBLICATION/);

    const output = join(root, "movie.mp4");
    await encodeCinematicSpan({span, output, directory: join(root, "graphics")});
    const result = JSON.parse(command("ffprobe", [
      "-v", "error",
      "-show_entries", "format=duration:stream=codec_name,codec_type,width,height,nb_frames",
      "-of", "json", output,
    ]));
    assert.equal(result.streams.length, 1,
      "Synthetic source audio must not leak into finished scene");
    assert.equal(result.streams[0].codec_name, "h264");
    assert.equal(Number(result.streams[0].nb_frames), 144);
    assert.equal(result.streams[0].width, 1280);
    assert.equal(result.streams[0].height, 720);
    assert.ok(Math.abs(Number(result.format.duration) - 6) < 0.1);

    await assert.rejects(() => planCinematicTimeline({
      ...inputs, beatVisualAssets: photoBeats.map((n, i) => i === 15 ? 0 : n),
    }), /photo-backed/);
    await assert.rejects(() => planCinematicTimeline({
      ...inputs, beatFrames: Array(19).fill(96),
    }), /cannot be looped or frozen/);
    await assert.rejects(() => planCinematicTimeline({
      ...inputs, manifest: {schemaVersion: 1, assets: [
        {...asset, endSceneId: "beat-19"},
      ]},
    }), /one to three/);
    await assert.rejects(() => planCinematicTimeline({
      ...inputs, manifest: {schemaVersion: 1, assets: [
        asset, {...asset, id: "repeat", sceneId: "beat-18", endSceneId: "beat-18"},
      ]},
    }), /Repeated SHA/);
  } finally {
    await rm(root, {recursive: true, force: true});
  }
});
